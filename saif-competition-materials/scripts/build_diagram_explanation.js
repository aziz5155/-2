function H1(text) {
  return new Paragraph({
    bidirectional: true, alignment: AlignmentType.RIGHT,
    spacing: { after: 200, before: 300 },
    border: { bottom: { color: ACCENT, space: 4, style: BorderStyle.SINGLE, size: 6 } },
    children: [new TextRun({ text, bold: true, size: 30, color: NAVY, rightToLeft: true, font: "Arial" })]
  });
}
function H2(text) {
  return new Paragraph({
    bidirectional: true, alignment: AlignmentType.RIGHT, spacing: { after: 130, before: 220 },
    children: [new TextRun({ text, bold: true, size: 25, color: ACCENT, rightToLeft: true, font: "Arial" })]
  });
}
function P(text, opts = {}) {
  return new Paragraph({
    bidirectional: true, alignment: AlignmentType.RIGHT, spacing: { after: opts.after ?? 130 },
    children: [new TextRun({ text, size: opts.size ?? 21, color: opts.color ?? "1A1A1A", bold: opts.bold, italics: opts.italics, rightToLeft: true, font: "Arial" })]
  });
}
function comp(num, title, body) {
  return new Paragraph({
    bidirectional: true, alignment: AlignmentType.RIGHT, spacing: { after: 110 },
    children: [
      new TextRun({ text: `(${num}) ${title} — `, bold: true, size: 21, color: NAVY, rightToLeft: true, font: "Arial" }),
      new TextRun({ text: body, size: 21, color: "1A1A1A", rightToLeft: true, font: "Arial" })
    ]
  });
}

